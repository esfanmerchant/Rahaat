<#
.SYNOPSIS
  Run the live Rahat demo on this Windows PC and publish it through a tunnel.

.DESCRIPTION
  npm run live:start    build a release from main, start the database, API and tunnel, print the URL
  npm run live:update   move the release to the newest main commit and restart the API (same URL)
  npm run live:stop     stop the API, the mock services and the tunnel (the data is kept)
  npm run live:status   show what is running, the health checks and the public URL
  npm run live:reset    wipe and reseed the live demo data

  Or directly:  powershell -ExecutionPolicy Bypass -File deploy\local\live.ps1 <command> [-Tunnel tailscale]

  Everything lives in .live\ (git-ignored): the release worktree, the database files, logs, secrets
  and the tunnel program. Secrets are generated once and kept in .live\secrets.env. Never commit or
  share that folder.

  The release is a separate git worktree at .live\app, pinned to one commit. Merging into main does
  not touch the running site; `update` moves it forward on purpose.

  Tunnels
    cloudflare (default)  no account needed. Each new tunnel gets a new random URL. `update` keeps the
                          tunnel running, so the URL changes only after `stop` or a reboot.
    tailscale             a stable URL. Install Tailscale, sign in and allow Funnel once
                          (deploy/README.md, section 3).

  Prototype. Not an official service. All identity, payment and data services are simulated.
#>
[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [ValidateSet('start', 'update', 'stop', 'status', 'reset')]
    [string]$Command = 'status',
    [string]$Ref = 'main',
    [ValidateSet('cloudflare', 'tailscale')]
    [string]$Tunnel = 'cloudflare',
    [int]$Port = 8080,
    [int]$MockPort = 9001
)

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

# Official Cloudflare build, pinned. Checksum from the GitHub release (asset digest and release notes).
$CloudflaredVersion = '2026.11.1'
$CloudflaredSha256 = '341deda3db5ec498a0482254d6c38c0b7cf01a30c37bb5dd95d2216d08955e35'

$Repo = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$Live = Join-Path $Repo '.live'
$App = Join-Path $Live 'app'
$Backend = Join-Path $App 'backend'
$Frontend = Join-Path $App 'frontend'
$Logs = Join-Path $Live 'logs'
$Bin = Join-Path $Live 'bin'
$PgData = Join-Path $Live 'pgdata'
$SecretsFile = Join-Path $Live 'secrets.env'
$StateFile = Join-Path $Live 'state.json'
$Cloudflared = Join-Path $Bin 'cloudflared.exe'
$VenvPython = Join-Path $Backend '.venv\Scripts\python.exe'

function Say([string]$Text) { Write-Host "[live] $Text" }

function Initialize-Folders {
    foreach ($dir in @($Live, $Logs, $Bin, $PgData)) {
        if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
    }
}

function Get-State {
    $state = @{}
    if (Test-Path $StateFile) {
        $saved = Get-Content $StateFile -Raw | ConvertFrom-Json
        foreach ($property in $saved.PSObject.Properties) { $state[$property.Name] = $property.Value }
    }
    return $state
}

function Save-State([hashtable]$State) {
    $State | ConvertTo-Json | Set-Content -Path $StateFile -Encoding ASCII
}

# Run one native command, all output to .live\logs\<name>.log. Show the end of the log if it fails.
function Invoke-Step([string]$Name, [string]$WorkDir, [string]$Exe, [string[]]$Arguments) {
    $log = Join-Path $Logs ($Name + '.log')
    Say $Name
    Push-Location $WorkDir
    $saved = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        & $Exe @Arguments *> $log
        $code = $LASTEXITCODE
    }
    finally {
        $ErrorActionPreference = $saved
        Pop-Location
    }
    if ($code -ne 0) {
        Get-Content $log -Tail 30 | ForEach-Object { Write-Host "    $_" }
        throw "$Name failed (exit code $code). Full log: $log"
    }
}

function New-RandomText([int]$Bytes, [switch]$UrlSafe) {
    $buffer = New-Object byte[] $Bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $rng.GetBytes($buffer)
    $rng.Dispose()
    $text = [Convert]::ToBase64String($buffer)
    if ($UrlSafe) { $text = $text.TrimEnd('=').Replace('+', '-').Replace('/', '_') }
    return $text
}

function Initialize-Secrets {
    if (-not (Test-Path $SecretsFile)) {
        $lines = @(
            '# Generated by deploy/local/live.ps1 for the live demo on this PC. Never commit or share.',
            ('SECRET_KEY=' + (New-RandomText 48 -UrlSafe)),
            ('MASTER_KEY=' + (New-RandomText 32)),
            ('APP_DB_PASSWORD=' + (New-RandomText 24 -UrlSafe))
        )
        Set-Content -Path $SecretsFile -Value $lines -Encoding ASCII
        Say 'generated new secrets in .live\secrets.env'
    }
    # Keys added later are appended, so an existing secrets file keeps its old values.
    $known = (Get-Content $SecretsFile) -join "`n"
    foreach ($name in @('MOCK_IDENTITY_KEY', 'MOCK_REGISTRY_KEY', 'MOCK_PAYMENT_KEY', 'MOCK_SMS_KEY', 'MOCK_CONTROL_KEY')) {
        if ($known -notmatch "(?m)^$name=") { Add-Content -Path $SecretsFile -Value ($name + '=' + (New-RandomText 24 -UrlSafe)) -Encoding ASCII }
    }
    foreach ($line in Get-Content $SecretsFile) {
        if ($line -match '^\s*#' -or $line -notmatch '=') { continue }
        $parts = $line.Split('=', 2)
        Set-Item -Path ('Env:' + $parts[0].Trim()) -Value $parts[1].Trim()
    }
}

function Set-LiveEnvironment {
    $env:APP_ENV = 'demo'
    $env:PYTHONUTF8 = '1'
    $env:PYTHONIOENCODING = 'utf-8'
    $env:NO_COLOR = '1'
    $env:UV_NO_PROGRESS = '1'
    $env:RAHAT_DEVDB_DIR = $PgData
    $env:MOCK_BASE_URL = "http://127.0.0.1:$MockPort"
    $env:PORT = "$Port"
    Remove-Item Env:DATABASE_URL -ErrorAction SilentlyContinue
}

function Update-Release {
    $sha = (& git -C $Repo rev-parse --verify --quiet "$Ref^{commit}")
    if (-not $sha) { throw "git cannot find '$Ref'" }
    $sha = $sha.Trim()
    if (-not (Test-Path (Join-Path $App '.git'))) {
        Invoke-Step 'release-worktree' $Repo 'git' @('worktree', 'add', '--detach', $App, $sha)
    }
    else {
        Invoke-Step 'release-checkout' $App 'git' @('checkout', '--detach', '--force', $sha)
    }
    Invoke-Step 'backend-install' $Backend 'uv' @('sync', '--frozen')
    $state = Get-State
    $lockHash = (Get-FileHash (Join-Path $Frontend 'package-lock.json') -Algorithm SHA256).Hash
    if ($state['npm_lock'] -ne $lockHash -or -not (Test-Path (Join-Path $Frontend 'node_modules'))) {
        Invoke-Step 'frontend-install' $Frontend 'npm' @('ci', '--no-audit', '--no-fund')
        $state['npm_lock'] = $lockHash
    }
    Invoke-Step 'frontend-build' $Frontend 'npm' @('run', 'build')
    $state['commit'] = $sha
    Save-State $state
    Say ("release is at " + $sha.Substring(0, 7))
}

function Start-Database {
    if ($env:DATABASE_URL_OWNER) {
        Say 'using the database named by DATABASE_URL_OWNER in .live\secrets.env'
        return
    }
    Invoke-Step 'database' $Backend 'uv' @('run', '--frozen', 'python', '-m', 'app.devdb', 'url', 'rahat_live')
    $url = Get-Content (Join-Path $Logs 'database.log') | Where-Object { $_ -match '^postgresql' } | Select-Object -Last 1
    if (-not $url) { throw 'could not start the live database; see .live\logs\database.log' }
    $env:DATABASE_URL_OWNER = $url.Trim()
}

function Start-Background([string]$Name, [string]$Exe, [string]$Arguments, [string]$WorkDir) {
    $process = Start-Process -FilePath $Exe -ArgumentList $Arguments -WorkingDirectory $WorkDir -WindowStyle Hidden `
        -RedirectStandardOutput (Join-Path $Logs "$Name.out.log") -RedirectStandardError (Join-Path $Logs "$Name.err.log") -PassThru
    return $process.Id
}

function Stop-ProcessTree([int]$Id) {
    if (-not $Id) { return }
    $children = Get-CimInstance Win32_Process -Filter "ParentProcessId=$Id" -ErrorAction SilentlyContinue
    foreach ($child in $children) { Stop-ProcessTree ([int]$child.ProcessId) }
    Stop-Process -Id $Id -Force -ErrorAction SilentlyContinue
}

function Test-Alive($Id) {
    if (-not $Id) { return $false }
    return [bool](Get-Process -Id ([int]$Id) -ErrorAction SilentlyContinue)
}

# Stop whatever uvicorn of ours still listens on a port (the venv launcher can leave a child behind).
function Stop-Listener([int]$OnPort) {
    $owners = Get-NetTCPConnection -LocalPort $OnPort -State Listen -ErrorAction SilentlyContinue |
        Select-Object -ExpandProperty OwningProcess -Unique
    foreach ($owner in $owners) {
        $info = Get-CimInstance Win32_Process -Filter "ProcessId=$owner" -ErrorAction SilentlyContinue
        if ($info -and $info.CommandLine -match 'uvicorn') { Stop-ProcessTree ([int]$owner) }
    }
}

function Wait-Http([string]$Url, [int]$Seconds, [string[]]$Extra = @()) {
    $deadline = (Get-Date).AddSeconds($Seconds)
    while ((Get-Date) -lt $deadline) {
        $code = & curl.exe -s -o NUL -w '%{http_code}' --max-time 8 @Extra $Url
        if ($code -eq '200') { return $true }
        Start-Sleep -Seconds 2
    }
    return $false
}

function Read-SharedText([string]$Path) {
    if (-not (Test-Path $Path)) { return '' }
    $stream = [System.IO.File]::Open($Path, 'Open', 'Read', 'ReadWrite')
    try { return (New-Object System.IO.StreamReader($stream)).ReadToEnd() }
    finally { $stream.Dispose() }
}

function Start-App {
    $state = Get-State
    if (Test-Path (Join-Path $Backend 'app\mocks\main.py')) {
        Stop-Listener $MockPort
        $state['mocks_pid'] = Start-Background 'mocks' $VenvPython "-m uvicorn app.mocks.main:app --host 127.0.0.1 --port $MockPort --workers 1" $Backend
        Say "mock services starting on 127.0.0.1:$MockPort"
    }
    # 127.0.0.1 only: nothing on the network reaches the API except through the tunnel on this PC, and
    # uvicorn trusts forwarded headers from 127.0.0.1 by default. One worker (in-process limits, job loop).
    $state['api_pid'] = Start-Background 'api' $VenvPython "-m uvicorn app.main:app --host 127.0.0.1 --port $Port --workers 1 --proxy-headers" $Backend
    Save-State $state
    if (-not (Wait-Http "http://127.0.0.1:$Port/readyz" 90)) {
        Get-Content (Join-Path $Logs 'api.err.log') -Tail 30 -ErrorAction SilentlyContinue | ForEach-Object { Write-Host "    $_" }
        throw "the API did not become ready on port $Port; see .live\logs\api.err.log"
    }
    Say "API ready on http://127.0.0.1:$Port"
}

function Stop-App {
    $state = Get-State
    Stop-ProcessTree $state['api_pid']
    Stop-ProcessTree $state['mocks_pid']
    Stop-Listener $Port
    Stop-Listener $MockPort
    $state['api_pid'] = $null
    $state['mocks_pid'] = $null
    Save-State $state
}

function Initialize-Cloudflared {
    if (Test-Path $Cloudflared) {
        if ((Get-FileHash $Cloudflared -Algorithm SHA256).Hash.ToLower() -eq $CloudflaredSha256) { return }
        Remove-Item $Cloudflared -Force
    }
    Say "downloading cloudflared $CloudflaredVersion (official Cloudflare build)"
    $download = Join-Path $Bin 'cloudflared.download'
    $source = "https://github.com/cloudflare/cloudflared/releases/download/$CloudflaredVersion/cloudflared-windows-amd64.exe"
    & curl.exe -sSL --max-time 300 -o $download $source
    if ($LASTEXITCODE -ne 0) { throw 'downloading cloudflared failed' }
    $actual = (Get-FileHash $download -Algorithm SHA256).Hash.ToLower()
    if ($actual -ne $CloudflaredSha256) {
        Remove-Item $download -Force
        throw "cloudflared checksum mismatch ($actual); not running it"
    }
    Move-Item $download $Cloudflared -Force
}

function Start-CloudflareTunnel {
    Initialize-Cloudflared
    $log = Join-Path $Logs 'tunnel.err.log'
    if (Test-Path $log) { Remove-Item $log -Force }
    # The quick-tunnel service sometimes times out. Try a few times; an error message that names
    # api.trycloudflare.com is not a tunnel URL, and a URL counts only once a connection is registered.
    for ($attempt = 1; $attempt -le 3; $attempt++) {
        if (Test-Path $log) { Remove-Item $log -Force }
        $tunnelId = Start-Background 'tunnel' $Cloudflared "tunnel --no-autoupdate --url http://127.0.0.1:$Port" $Live
        $deadline = (Get-Date).AddSeconds(90)
        $url = $null
        $registered = $false
        while ((Get-Date) -lt $deadline) {
            $text = Read-SharedText $log
            $match = [regex]::Match($text, 'https://(?!api\.)[a-z0-9-]+\.trycloudflare\.com')
            if ($match.Success) { $url = $match.Value }
            if ($url -and $text -match 'Registered tunnel connection') { $registered = $true; break }
            if (-not (Test-Alive $tunnelId)) { break }
            Start-Sleep -Seconds 2
        }
        if ($registered) { return @{ pid = $tunnelId; url = $url } }
        if (Test-Alive $tunnelId) { Stop-ProcessTree $tunnelId }
        Say "the tunnel did not come up (attempt $attempt of 3)"
        Start-Sleep -Seconds (5 * $attempt)
    }
    Read-SharedText $log | Write-Host
    throw 'the Cloudflare tunnel did not start; see .live\logs\tunnel.err.log'
}

function Start-TailscaleTunnel {
    $tailscale = Get-Command tailscale.exe -ErrorAction SilentlyContinue
    if (-not $tailscale) { throw 'Tailscale is not installed. See deploy/README.md, section 3, then run again with -Tunnel tailscale.' }
    Invoke-Step 'tailscale-funnel' $Live $tailscale.Source @('funnel', '--bg', "http://127.0.0.1:$Port")
    $status = (& $tailscale.Source status --json | Out-String) | ConvertFrom-Json
    $name = ([string]$status.Self.DNSName).TrimEnd('.')
    if (-not $name) { throw 'Tailscale did not report a DNS name. Is this PC signed in?' }
    return @{ pid = $null; url = "https://$name" }
}

function Confirm-Public([string]$Url) {
    if (Wait-Http "$Url/healthz" 45) { return $true }
    # A brand-new hostname can be cached as "not found" by this PC; ask a public resolver instead.
    return (Wait-Http "$Url/healthz" 45 @('--doh-url', 'https://cloudflare-dns.com/dns-query'))
}

function Show-Status {
    $state = Get-State
    $commit = if ($state['commit']) { ([string]$state['commit']).Substring(0, 7) } else { 'none' }
    Say ("release commit: " + $commit)
    Say ("API:     " + $(if (Test-Alive $state['api_pid']) { "running (pid $($state['api_pid']))" } else { 'stopped' }))
    Say ("mocks:   " + $(if (Test-Alive $state['mocks_pid']) { "running (pid $($state['mocks_pid']))" } else { 'not running' }))
    Say ("tunnel:  " + $(if ($state['tunnel'] -eq 'tailscale') { 'tailscale funnel' } elseif (Test-Alive $state['tunnel_pid']) { "cloudflare (pid $($state['tunnel_pid']))" } else { 'stopped' }))
    $local = & curl.exe -s -o NUL -w '%{http_code}' --max-time 5 "http://127.0.0.1:$Port/readyz"
    Say ("local readyz: " + $local)
    if ($state['url']) {
        $public = & curl.exe -s -o NUL -w '%{http_code}' --max-time 10 "$($state['url'])/healthz"
        Say ("public URL:   " + $state['url'] + "  (healthz " + $public + ")")
    }
}

Initialize-Folders
switch ($Command) {
    'status' { Show-Status }

    'start' {
        $state = Get-State
        if (Test-Alive $state['api_pid']) { Say 'already running. Use update to deploy newer code, or stop first.'; Show-Status; break }
        Initialize-Secrets
        Set-LiveEnvironment
        Update-Release
        Start-Database
        Invoke-Step 'migrate' $Backend 'uv' @('run', '--frozen', 'alembic', 'upgrade', 'head')
        Invoke-Step 'seed' $Backend 'uv' @('run', '--frozen', 'python', '-m', 'app.seed')
        Start-App
        $state = Get-State
        if ($Tunnel -eq 'cloudflare' -and (Test-Alive $state['tunnel_pid']) -and $state['url']) {
            Say 'tunnel already running; keeping its URL'
        }
        else {
            $result = if ($Tunnel -eq 'tailscale') { Start-TailscaleTunnel } else { Start-CloudflareTunnel }
            $state['tunnel'] = $Tunnel
            $state['tunnel_pid'] = $result.pid
            $state['url'] = $result.url
        }
        $state['started_at'] = (Get-Date).ToString('s')
        Save-State $state
        if (Confirm-Public $state['url']) { Say "PUBLIC URL: $($state['url'])" }
        else { Say "tunnel is up but $($state['url']) did not answer yet; try live:status in a minute" }
    }

    'update' {
        Initialize-Secrets
        Set-LiveEnvironment
        Stop-App
        Update-Release
        Start-Database
        Invoke-Step 'migrate' $Backend 'uv' @('run', '--frozen', 'alembic', 'upgrade', 'head')
        Invoke-Step 'seed' $Backend 'uv' @('run', '--frozen', 'python', '-m', 'app.seed')
        Start-App
        $state = Get-State
        if ($state['tunnel'] -ne 'tailscale' -and -not (Test-Alive $state['tunnel_pid'])) {
            $result = Start-CloudflareTunnel
            $state['tunnel'] = 'cloudflare'
            $state['tunnel_pid'] = $result.pid
            $state['url'] = $result.url
            Save-State $state
            Say 'the tunnel had stopped, so the public URL is new'
        }
        Say "updated. PUBLIC URL: $($state['url'])"
    }

    'stop' {
        Stop-App
        $state = Get-State
        if ($state['tunnel'] -eq 'tailscale') {
            $tailscale = Get-Command tailscale.exe -ErrorAction SilentlyContinue
            if ($tailscale) { Invoke-Step 'tailscale-funnel-off' $Live $tailscale.Source @('funnel', 'reset') }
        }
        else { Stop-ProcessTree $state['tunnel_pid'] }
        $state['tunnel_pid'] = $null
        Save-State $state
        Say 'stopped the API, mock services and tunnel. The database and its data are kept.'
    }

    'reset' {
        Initialize-Secrets
        Set-LiveEnvironment
        Start-Database
        Invoke-Step 'seed-reset' $Backend 'uv' @('run', '--frozen', 'python', '-m', 'app.seed', '--reset')
        Say 'live demo data wiped and reseeded'
    }
}
